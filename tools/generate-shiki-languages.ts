#!/usr/bin/env node
import {writeFile} from 'node:fs/promises';
import {bundledLanguagesInfo} from 'shiki/langs';

// the diff viewer loads the precompiled grammars one by one, so every import has to be a literal for the bundler
const entries = bundledLanguagesInfo.map((info) => {
  const key = /^[a-z][a-z0-9]*$/.test(info.id) ? info.id : `'${info.id}'`;
  const aliases = (info.aliases ?? []).map((alias) => `'${alias}'`).join(', ');
  return `  ${key}: {name: '${info.name.replaceAll(`'`, `\\'`)}', aliases: [${aliases}], load: () => import('@shikijs/langs-precompiled/${info.id}')},`;
});

const out = `// Generated by tools/generate-shiki-languages.ts, do not edit
import type {LanguageRegistration} from '@shikijs/core';

export type ShikiLanguage = {name: string; aliases: string[]; load: () => Promise<{default: LanguageRegistration[]}>};

export const shikiLanguages: Record<string, ShikiLanguage> = {
${entries.join('\n')}
};
`;

const outPath = new URL('../web_src/js/modules/diffviewer/shiki-languages.ts', import.meta.url);
await writeFile(outPath, out);
console.info(`wrote ${entries.length} languages to ${outPath.pathname}`);
