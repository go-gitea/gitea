func TestGerritErrors(t *testing.T) {
	var status int
	var retryAfter string
	var calls int
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		calls++
		switch r.URL.Path {
		case "/projects/demo":
			if status != http.StatusOK && calls <= 2 {
				if retryAfter != "" {
					w.Header().Set("Retry-After", retryAfter)
				}
				w.WriteHeader(status)
				return
			}
			writeGerritJSON(w, map[string]any{"name": "demo"})
		case "/changes/":
			_, _ = w.Write([]byte("<html>login</html>"))
		default:
			w.WriteHeader(http.StatusForbidden)
		}
	}))
	defer srv.Close()

	newDownloader := func() (*GerritDownloader, *[]time.Duration) {
		var waits []time.Duration
		d := newTestGerritDownloader(t, srv.URL+"/demo", base.MigrateOptions{})
		d.sleep = func(_ context.Context, wait time.Duration) error {
			waits = append(waits, wait)
			return nil
		}
		return d, &waits
	}

	t.Run("RateLimitUsesRetryAfter", func(t *testing.T) {
		status, retryAfter, calls = http.StatusTooManyRequests, "3", 0
		d, waits := newDownloader()
		require.NoError(t, d.resolve(t.Context()))
		assert.Equal(t, []time.Duration{3 * time.Second, 3 * time.Second}, *waits)
	})
	t.Run("TemporaryErrorBacksOff", func(t *testing.T) {
		status, retryAfter, calls = http.StatusServiceUnavailable, "", 0
		d, waits := newDownloader()
		require.NoError(t, d.resolve(t.Context()))
		assert.Equal(t, []time.Duration{time.Second, 2 * time.Second}, *waits)
		assert.Equal(t, time.Minute, gerritRetryAfter("100000", 1))
	})
	t.Run("NeverRecovers", func(t *testing.T) {
		status, retryAfter, calls = http.StatusBadGateway, "", -100
		d, waits := newDownloader()
		err := d.resolve(t.Context())
		statusErr, ok := err.(*gerritStatusError)
		require.True(t, ok, err)
		assert.Equal(t, http.StatusBadGateway, statusErr.Status)
		assert.Len(t, *waits, gerritMaxAttempts-1)
	})
	t.Run("AuthenticationError", func(t *testing.T) {
		d := newTestGerritDownloader(t, srv.URL+"/demo", base.MigrateOptions{})
		d.resolved, d.root, d.project = true, srv.URL, "other"
		err := d.callAPI(t.Context(), srv.URL, "/projects/other", nil, &struct{}{})
		require.Error(t, err)
		assert.True(t, IsAuthenticationError(err))
	})
	t.Run("NotJSON", func(t *testing.T) {
		status = http.StatusOK
		d, _ := newDownloader()
		_, _, err := d.GetPullRequests(t.Context(), 1, 10)
		require.ErrorContains(t, err, "invalid response")
	})
}

func TestParseGerritVotes(t *testing.T) {
	patchSet, votes := parseGerritVotes("Patch Set 12: Code-Review-2 Verified+1 -Foo\n\ntext Code-Review+2")
	assert.Equal(t, 12, patchSet)
	assert.Equal(t, []gerritVote{{"Code-Review", -2}, {"Verified", 1}}, votes)
	assert.Equal(t, base.ReviewStateChangesRequested, gerritReviewState(votes))
	assert.Equal(t, base.ReviewStateCommented, gerritReviewState([]gerritVote{{"Code-Review", 0}, {"Verified", 1}}))

	patchSet, votes = parseGerritVotes("Just a message")
	assert.Zero(t, patchSet)
	assert.Empty(t, votes)
}
