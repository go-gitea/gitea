func (f *gerritFixture) cloneAddr() string {
	return f.server.URL + "/gerrit/team/demo.git"
}

func (f *gerritFixture) serveGit(w http.ResponseWriter, r *http.Request) bool {
	if !strings.HasPrefix(r.URL.Path, "/gerrit/team/demo/") {
		return false
	}
	backend, err := exec.LookPath("git")
	if err != nil {
		http.Error(w, err.Error(), http.StatusInternalServerError)
		return true
	}
	execPath, err := exec.CommandContext(r.Context(), backend, "--exec-path").Output()
	if err != nil {
		http.Error(w, err.Error(), http.StatusInternalServerError)
		return true
	}
	(&cgi.Handler{
		Path:       filepath.Join(strings.TrimSpace(string(execPath)), "git-http-backend"),
		Root:       "/gerrit",
		Env:        []string{"GIT_PROJECT_ROOT=" + f.gitRoot, "GIT_HTTP_EXPORT_ALL=1"},
		InheritEnv: []string{"PATH", "HOME"},
	}).ServeHTTP(w, r)
	return true
}

func writeGerritJSON(w http.ResponseWriter, v any) {
	data, _ := json.Marshal(v)
	_, _ = w.Write([]byte(")]}'\n"))
	_, _ = w.Write(data)
}

func (f *gerritFixture) handle(w http.ResponseWriter, r *http.Request) {
	if f.serveGit(w, r) {
		return
	}
	f.mu.Lock()
	defer f.mu.Unlock()
	f.authHeaders = append(f.authHeaders, r.Header.Get("Authorization"))

	path, ok := strings.CutPrefix(r.URL.Path, "/gerrit")
	if !ok {
		http.NotFound(w, r)
		return
	}
	if rest, isAuth := strings.CutPrefix(path, "/a/"); isAuth {
		if r.Header.Get("Authorization") == "" {
			w.WriteHeader(http.StatusUnauthorized)
			return
		}
		path = "/" + rest
	}
	switch {
	case path == "/projects/gerrit/team/demo":
		_, _ = w.Write([]byte("<html>not a Gerrit</html>"))
	case path == "/projects/team/demo":
		writeGerritJSON(w, map[string]any{"name": "team/demo", "description": "demo project"})
	case path == "/projects/team/demo/HEAD":
		writeGerritJSON(w, "refs/heads/main")
	case path == "/changes/":
		f.listCalls++
		start, _ := strconv.Atoi(r.URL.Query().Get("S"))
		var page []map[string]any
		for number := int64(start + 1); number <= 3 && len(page) < 2; number++ {
			page = append(page, map[string]any{"_number": number})
		}
		if len(page) > 0 && start+len(page) < 3 {
			page[len(page)-1]["_more_changes"] = true
		}
		writeGerritJSON(w, page)
	case strings.HasPrefix(path, "/changes/team/demo~"):
		rest := strings.TrimPrefix(path, "/changes/team/demo~")
		numberText, isComments := strings.CutSuffix(rest, "/comments")
		number, _ := strconv.ParseInt(numberText, 10, 64)
		if isComments {
			f.commentCalls++
			writeGerritJSON(w, f.comments[number])
		} else if change, ok := f.changes[number]; ok {
			writeGerritJSON(w, change)
		} else {
			http.NotFound(w, r)
		}
	default:
		http.NotFound(w, r)
	}
}

