// This file implements the static LocaleStore that will not watch for changes

type locale struct {
	store       *localeStore
	langName    string
	langTag     language.Tag
	idxToMsgMap map[int]string // the map idx is generated by store's trKeyToIdxMap
}

var _ Locale = (*locale)(nil)

type localeStore struct {
	// After initializing has finished, these fields are read-only.
	langNames []string
	langDescs []string

	localeMap     map[string]*locale
	trKeyToIdxMap map[string]int

	defaultLang string
}

// NewLocaleStore creates a static locale store
func NewLocaleStore() LocaleStore {
	return &localeStore{localeMap: make(map[string]*locale), trKeyToIdxMap: make(map[string]int)}
}

// AddLocaleByJSON adds locale by JSON into the store
func (store *localeStore) AddLocaleByJSON(langName, langDesc string, source, moreSource []byte) error {
	if _, ok := store.localeMap[langName]; ok {
		return errors.New("lang has already been added")
	}

	store.langNames = append(store.langNames, langName)
	store.langDescs = append(store.langDescs, langDesc)

	l := &locale{store: store, langName: langName, langTag: parseLangTag(langName), idxToMsgMap: make(map[int]string)}
	store.localeMap[l.langName] = l

	addFunc := func(source []byte) error {
		if len(source) == 0 {
			return nil
		}

		values := make(map[string]any)
		if err := json.Unmarshal(source, &values); err != nil {
			return fmt.Errorf("unable to load json: %w", err)
		}
		for trKey, value := range values {
			switch v := value.(type) {
			case string:
				idx, ok := store.trKeyToIdxMap[trKey]
				if !ok {
					idx = len(store.trKeyToIdxMap)
					store.trKeyToIdxMap[trKey] = idx
				}
				l.idxToMsgMap[idx] = v
			case map[string]any:
				for key, val := range v {
					valStr, ok := val.(string)
					if !ok {
						return fmt.Errorf("unsupported value type %T for key %q", val, trKey+"."+key)
					}
					idx, ok := store.trKeyToIdxMap[trKey+"."+key]
					if !ok {
						idx = len(store.trKeyToIdxMap)
						store.trKeyToIdxMap[trKey+"."+key] = idx
					}
					l.idxToMsgMap[idx] = valStr
				}
			default:
				return fmt.Errorf("unsupported value type %T for key %q", v, trKey)
			}
		}
		return nil
	}

	if err := addFunc(source); err != nil {
		return fmt.Errorf("unable to load json: %w", err)
	}
	if err := addFunc(moreSource); err != nil {
		return fmt.Errorf("unable to load json: %w", err)
	}
	return nil
}

func (store *localeStore) HasLang(langName string) bool {
	_, ok := store.localeMap[langName]
	return ok
}

func (store *localeStore) ListLangNameDesc() (names, desc []string) {
	return store.langNames, store.langDescs
}

// SetDefaultLang sets default language as a fallback
func (store *localeStore) SetDefaultLang(lang string) {
	store.defaultLang = lang
}

// Locale returns the locale for the lang or the default language
func (store *localeStore) Locale(lang string) (Locale, bool) {
	l, found := store.localeMap[lang]
	if !found {
		var ok bool
		l, ok = store.localeMap[store.defaultLang]
		if !ok {
			// no default - return an empty locale
			l = &locale{store: store, idxToMsgMap: make(map[int]string)}
		}
	}
	return l, found
}

func (store *localeStore) Close() error {
	return nil
}

func (l *locale) TrString(trKey string, trArgs ...any) string {
	var format string
	idx, ok := l.store.trKeyToIdxMap[trKey]
	if ok {
		format = l.idxToMsgMap[idx]
		if format == "" { // missing translation in this locale, fallback to default
			if def, ok := l.store.localeMap[l.store.defaultLang]; ok {
				// try to use default locale's translation
				format = def.idxToMsgMap[idx]
			}
		}
	}
	if format == "" { // still missing, use the key itself
		format = html.EscapeString(trKey)
	}
	msg, err := Format(format, trArgs...)
	if err != nil {
		log.Error("Error whilst formatting %q in %s: %v", trKey, l.langName, err)
	}
	return msg
}

func escapeTrArgs(trArgs []any) []any {
	args := slices.Clone(trArgs)
	for i, v := range args {
		switch v := v.(type) {
		case nil, bool, int, int8, int16, int32, int64, uint, uint8, uint16, uint32, uint64, float32, float64, template.HTML:
			// for most basic types (including template.HTML which is safe), just do nothing and use it
		case string:
			args[i] = template.HTMLEscapeString(v)
		case fmt.Stringer:
			args[i] = template.HTMLEscapeString(v.String())
		default:
			args[i] = template.HTMLEscapeString(fmt.Sprint(v))
		}
	}
	return args
}

func (l *locale) TrHTML(trKey string, trArgs ...any) template.HTML {
	return template.HTML(l.TrString(trKey, escapeTrArgs(trArgs)...))
}

func parseLangTag(langName string) language.Tag {
	return language.Make(langName) // lenient, e.g. keeps the language part if the region is unknown
}

// pluralCategory returns the CLDR cardinal plural category name (zero/one/two/few/many/other) of cnt in this locale's language
func (l *locale) pluralCategory(cnt int64) string {
	if cnt < 0 {
		cnt = -cnt
	}
	switch plural.Cardinal.MatchPlural(l.langTag, int(cnt), 0, 0, 0, 0) {
	case plural.Zero:
		return "zero"
	case plural.One:
		return "one"
	case plural.Two:
		return "two"
	case plural.Few:
		return "few"
	case plural.Many:
		return "many"
	}
	return "other"
}

func (l *locale) ownMsg(trKey string) string {
	if idx, ok := l.store.trKeyToIdxMap[trKey]; ok {
		return l.idxToMsgMap[idx]
	}
	return ""
}

// pluralMsg picks the message of this locale only (no default-language fallback), in this order:
// "<key>.<category>", "<key>.other", then "<key>" itself (the legacy plain-string form).
func (l *locale) pluralMsg(trKey string, cnt int64) string {
	if msg := l.ownMsg(trKey + "." + l.pluralCategory(cnt)); msg != "" {
		return msg
	}
	if msg := l.ownMsg(trKey + ".other"); msg != "" {
		return msg
	}
	return l.ownMsg(trKey)
}

// HasPluralKey reports whether this locale itself (without fallback) provides CLDR plural forms for the key
func (l *locale) HasPluralKey(trKey string) bool {
	return l.ownMsg(trKey+".other") != ""
}

// TrPluralString translates a key by the CLDR plural category of cnt.
// A plural message is declared as a nested JSON object, which is flattened to "<key>.<category>" keys:
//
//	"tool.days": {"one": "%d day", "other": "%d days"}
//
// If a locale only has the legacy plain string for the key, that string is used for every count.
// Missing translations fall back to the default locale (using its own plural rules), then to the key itself.
func (l *locale) TrPluralString(trKey string, cnt int64, trArgs ...any) string {
	format := l.pluralMsg(trKey, cnt)
	if format == "" {
		if def, ok := l.store.localeMap[l.store.defaultLang]; ok && def != l {
			format = def.pluralMsg(trKey, cnt)
		}
	}
	if format == "" {
		format = html.EscapeString(trKey)
	}
	msg, err := Format(format, trArgs...)
	if err != nil {
		log.Error("Error whilst formatting %q in %s: %v", trKey, l.langName, err)
	}
	return msg
}

func (l *locale) HasOwnKey(trKey string) bool {
	return l.ownMsg(trKey) != ""
}

var pluralCategories = []string{"zero", "one", "two", "few", "many", "other"}

func (l *locale) PluralForms(trKey string) map[string]string {
	collect := func(loc *locale) map[string]string {
		forms := map[string]string{}
		for _, c := range pluralCategories {
			if msg := loc.ownMsg(trKey + "." + c); msg != "" {
				forms[c] = msg
			}
		}
		return forms
	}
	forms := collect(l)
	if len(forms) == 0 {
		if def, ok := l.store.localeMap[l.store.defaultLang]; ok && def != l {
			forms = collect(def)
		}
	}
	return forms
}

func (l *locale) TrPluralHTML(trKey string, cnt int64, trArgs ...any) template.HTML {
	return template.HTML(l.TrPluralString(trKey, cnt, escapeTrArgs(trArgs)...))
}

// HasKey returns whether a key is present in this locale or not
func (l *locale) HasKey(trKey string) bool {
	idx, ok := l.store.trKeyToIdxMap[trKey]
	if !ok {
		return false
	}
	_, ok = l.idxToMsgMap[idx]
	if !ok {
		_, ok = l.store.localeMap[l.store.defaultLang]
	}
	return ok
}
