//go:build ignore

package main

import (
	"bufio"
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"log"
	"net/http"
	"os"
	"regexp"
	"slices"
	"strings"

	"gitea.dev/modules/json"
)

const (
	emojiTestURL = "https://www.unicode.org/Public/17.0.0/emoji/emoji-test.txt"
	jsonFile     = "assets/emoji.json"
	goFile       = "modules/emoji/emoji_data.go"
)

type emoji struct {
	code        string
	description string
	aliases     []string
}

var slugRe = regexp.MustCompile(`[^a-z0-9]+`)

func main() {
	if err := generate(); err != nil {
		log.Fatal(err)
	}
}

func generate() error {
	// assets/emoji.json is also the alias source, so existing aliases stay stable
	existing, err := os.ReadFile(jsonFile)
	if err != nil {
		return err
	}
	var existingAliases map[string][]string
	if err := json.Unmarshal(existing, &existingAliases); err != nil {
		return err
	}

	emojis, err := fetchEmojis(existingAliases)
	if err != nil {
		return err
	}

	jsonData, err := marshalJSON(emojis)
	if err != nil {
		return err
	}
	if err := os.WriteFile(jsonFile, jsonData, 0o644); err != nil {
		return err
	}

	goData, err := marshalGo(emojis)
	if err != nil {
		return err
	}
	return os.WriteFile(goFile, goData, 0o644)
}

func isSkinTone(r rune) bool {
	return r >= 0x1f3fb && r <= 0x1f3ff
}

func fetchEmojis(existingAliases map[string][]string) ([]*emoji, error) {
	res, err := http.Get(emojiTestURL)
	if err != nil {
		return nil, err
	}
	defer res.Body.Close()
	if res.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("fetching %s: %s", emojiTestURL, res.Status)
	}

	var emojis []*emoji
	scanner := bufio.NewScanner(res.Body)
	for scanner.Scan() {
		// e.g. "1F44D ; fully-qualified # 👍 E0.6 thumbs up"
		_, rest, _ := strings.Cut(scanner.Text(), ";")
		status, comment, _ := strings.Cut(rest, "#")
		if strings.TrimSpace(status) != "fully-qualified" {
			continue
		}
		fields := strings.SplitN(strings.TrimSpace(comment), " ", 3)
		if strings.ContainsFunc(fields[0], isSkinTone) {
			continue
		}
		emojis = append(emojis, &emoji{code: fields[0], description: fields[2]})
	}
	if err := scanner.Err(); err != nil {
		return nil, err
	}

	var errs []error
	aliasOwners := map[string]string{}
	for _, e := range emojis {
		e.aliases = existingAliases[e.code]
		if e.aliases == nil {
			e.aliases = []string{strings.Trim(slugRe.ReplaceAllString(strings.ReplaceAll(strings.ToLower(e.description), "’", ""), "_"), "_")}
		}
		delete(existingAliases, e.code)
		for _, alias := range e.aliases {
			if owner, ok := aliasOwners[alias]; ok {
				errs = append(errs, fmt.Errorf("alias %q used by both %q and %q", alias, owner, e.code))
			}
			aliasOwners[alias] = e.code
		}
	}
	for code, aliases := range existingAliases {
		errs = append(errs, fmt.Errorf("emoji %q with aliases %v is missing from Unicode data", code, aliases))
	}
	if len(errs) > 0 {
		return nil, errors.Join(errs...)
	}

	slices.SortFunc(emojis, func(a, b *emoji) int {
		return strings.Compare(a.aliases[0], b.aliases[0])
	})
	return emojis, nil
}

func marshalJSON(emojis []*emoji) ([]byte, error) {
	// a Go map would lose the alias ordering the frontend relies on
	var buf bytes.Buffer
	buf.WriteByte('{')
	for i, e := range emojis {
		if i > 0 {
			buf.WriteByte(',')
		}
		key, err := json.Marshal(e.code)
		if err != nil {
			return nil, err
		}
		value, err := json.Marshal(e.aliases)
		if err != nil {
			return nil, err
		}
		buf.Write(key)
		buf.WriteByte(':')
		buf.Write(value)
	}
	buf.WriteByte('}')
	var out bytes.Buffer
	if err := json.Indent(&out, buf.Bytes(), "", "  "); err != nil {
		return nil, err
	}
	out.WriteByte('\n')
	return out.Bytes(), nil
}

func marshalGo(emojis []*emoji) ([]byte, error) {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, `// Copyright 2020 The Gitea Authors. All rights reserved.
// SPDX-License-Identifier: MIT

package emoji

// Code generated by build/generate-emoji.go. DO NOT EDIT.
// Sourced from %s
var GemojiData = Gemoji{
`, emojiTestURL)
	for _, e := range emojis {
		fmt.Fprintf(&buf, "\t{%q, %q, %#v},\n", e.code, e.description, e.aliases)
	}
	buf.WriteString("}\n")
	return format.Source(buf.Bytes())
}
